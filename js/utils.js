// Couleur de texte lisible (noir ou blanc) sur un fond donné, d'après sa luminance relative
// Readable text colour (black or white) on a given background, from its relative luminance
export function textColorFor(hex) {
  const match = /^#([0-9a-f]{6})$/i.exec(hex || '');
  if (!match) return '#fff';
  const channels = [0, 2, 4].map((start) => {
    const value = parseInt(match[1].slice(start, start + 2), 16) / 255;
    return value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  });
  const luminance = 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
  return luminance > 0.35 ? '#111' : '#fff';
}

// ---------- Dates ----------

// Date locale AAAA-MM-JJ (pas UTC, sinon décalage le soir) / Local date, not UTC
export function toLocalDateString(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

export function formatTime(timestamp) {
  return new Date(timestamp).toLocaleTimeString('fr-FR', { hour: '2-digit', minute: '2-digit' });
}

// ---------- Identifiants / IDs ----------
export function newId() {
  return (crypto.randomUUID && crypto.randomUUID()) || `${Date.now()}-${Math.random().toString(16).slice(2)}`;
}

// ---------- Interface : erreurs, toasts, dialogues / UI: errors, toasts, dialogs ----------

// Affiche une erreur bien visible, jamais en silence / Show a visible error, never silent
export function showError(message, error) {
  console.error(message, error);
  const banner = document.getElementById('error-banner');
  const detail = error && error.message ? ` (${error.message})` : '';
  banner.textContent = `⚠️ ${message}${detail}`;
  banner.hidden = false;
  banner.onclick = () => { banner.hidden = true; }; // toucher pour fermer / tap to dismiss
}

let toastTimer = null;
export function showToast(message) {
  const toast = document.getElementById('toast');
  toast.textContent = message;
  toast.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { toast.hidden = true; }, 1800);
}

// Dialogue de confirmation, renvoie une Promesse<boolean> / Confirm dialog, returns Promise<boolean>
export function confirmDialog(message, { confirmLabel = 'Confirmer', danger = false } = {}) {
  return new Promise((resolve) => {
    const dialog = document.getElementById('dialog');
    dialog.innerHTML = '';
    const text = document.createElement('p');
    text.textContent = message;
    const actions = document.createElement('div');
    actions.className = 'dialog-actions';
    const cancelButton = makeButton('Annuler', 'btn');
    const okButton = makeButton(confirmLabel, danger ? 'btn btn-danger' : 'btn btn-primary');
    actions.append(cancelButton, okButton);
    dialog.append(text, actions);
    const close = (result) => { dialog.close(); resolve(result); };
    cancelButton.onclick = () => close(false);
    okButton.onclick = () => close(true);
    dialog.oncancel = (event) => { event.preventDefault(); close(false); };
    dialog.showModal();
  });
}

// Menu d'actions : une liste de gros boutons empilés. actions = [{ label, run, danger? }].
// L'action choisie est exécutée APRÈS la fermeture du menu (elle peut donc ouvrir un autre dialogue).
// Action menu: a list of big stacked buttons. The chosen action runs AFTER the menu is closed
// (so it can open another dialog).
export function actionDialog(title, actions) {
  return new Promise((resolve) => {
    const dialog = document.getElementById('dialog');
    dialog.innerHTML = '';
    const list = el('div', 'action-list');
    actions.forEach((action) => {
      const button = makeButton(action.label, 'btn action-btn' + (action.danger ? ' btn-danger' : ''));
      // On ferme d'abord (effet immédiat), puis on lance l'action qui peut rouvrir un dialogue
      // Close first (immediate effect), then run the action which may reopen a dialog
      button.onclick = () => { dialog.close(); resolve(action.run()); };
      list.append(button);
    });
    const closeButton = makeButton('Fermer', 'btn action-btn');
    closeButton.onclick = () => { dialog.close(); resolve(); };
    list.append(closeButton);
    dialog.append(el('h3', '', title), list);
    dialog.oncancel = () => resolve(); // touche Retour : fermeture normale / Back key: normal close
    dialog.showModal();
  });
}

// Dialogue de formulaire. buildBody(container) remplit le formulaire ; validate() renvoie un message
// d'erreur (texte) ou rien si tout est correct. Résout true (OK) ou false (annulé).
// Form dialog. buildBody(container) fills the form; validate() returns an error message (string)
// or nothing when valid. Resolves true (OK) or false (cancelled).
export function formDialog(title, buildBody, validate, confirmLabel = 'Enregistrer') {
  return new Promise((resolve) => {
    const dialog = document.getElementById('dialog');
    dialog.innerHTML = '';
    const body = el('div', 'form-body');
    buildBody(body);
    const errorLine = el('p', 'form-error', '');
    const actions = el('div', 'dialog-actions');
    const cancelButton = makeButton('Annuler', 'btn');
    const okButton = makeButton(confirmLabel, 'btn btn-primary');
    actions.append(cancelButton, okButton);
    dialog.append(el('h3', '', title), body, errorLine, actions);
    const close = (result) => { dialog.close(); resolve(result); };
    cancelButton.onclick = () => close(false);
    okButton.onclick = () => {
      const message = validate();
      if (message) { errorLine.textContent = message; return; }
      close(true);
    };
    dialog.oncancel = (event) => { event.preventDefault(); close(false); };
    dialog.showModal();
  });
}

export function makeButton(label, className = 'btn') {
  const button = document.createElement('button');
  button.type = 'button';
  button.className = className;
  button.textContent = label;
  return button;
}

// Petit constructeur d'éléments / Small element builder
export function el(tag, className, text) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  if (text !== undefined) element.textContent = text;
  return element;
}
