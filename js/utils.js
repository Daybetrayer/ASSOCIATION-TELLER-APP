// ---------- Argent / Money (toujours en centimes / always in cents) ----------

// 250 -> "2,50 €"
export function formatMoney(cents, currency = '€') {
  const amount = (cents / 100).toLocaleString('fr-FR', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  return `${amount} ${currency}`;
}

// "2,5" ou "2.50" -> 250 ; texte invalide -> null / invalid text -> null
export function parseEurosToCents(text) {
  const cleaned = String(text).trim().replace(',', '.');
  if (cleaned === '' || isNaN(Number(cleaned))) return null;
  return Math.round(Number(cleaned) * 100);
}

// 250 -> "2,50" (sans devise, pour les CSV) / without currency, for CSV files
export function formatDecimal(cents) {
  return (cents / 100).toFixed(2).replace('.', ',');
}

// ---------- Export de fichiers / File export ----------

// Construit un CSV compatible Excel/LibreOffice FR : BOM UTF-8, séparateur « ; », fin de ligne CRLF
// Builds a CSV for French Excel/LibreOffice: UTF-8 BOM, ";" separator, CRLF line ends
export function toCsv(rows) {
  const escapeCell = (value) => {
    let text = String(value ?? '');
    // Évite l'exécution de formules par le tableur / Prevent spreadsheet formula injection
    if (/^[=+\-@]/.test(text) && isNaN(Number(text.replace(',', '.')))) text = `'${text}`;
    return /[";\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
  };
  return '﻿' + rows.map((row) => row.map(escapeCell).join(';')).join('\r\n');
}

// Télécharge un fichier généré par l'application / Downloads a file generated by the app
export function downloadFile(fileName, content, mimeType) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10000);
}

